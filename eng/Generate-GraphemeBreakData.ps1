<#
.SYNOPSIS
    Regenerates src/LoomEditor.Core/Text/GraphemeBreakData.cs from Monaco's grapheme break table.

.DESCRIPTION
    Downloads src/vs/base/common/strings.ts at the pinned upstream commit, extracts the integer array that
    getGraphemeBreakRawData() parses with JSON.parse, and writes it as a C# collection expression
    (24 values per line). Fails when the number of values is not a multiple of 3.

.EXAMPLE
    ./eng/Generate-GraphemeBreakData.ps1
#>
$ErrorActionPreference = 'Stop'

$commit = '0c9c0a4295a9222e12a605537738719455ae3056'
$url = "https://raw.githubusercontent.com/microsoft/vscode/$commit/src/vs/base/common/strings.ts"
$source = (Invoke-WebRequest -Uri $url -UseBasicParsing).Content

$match = [regex]::Match($source, "JSON\.parse\('\[([0-9,\s]+)\]'\)")
if (-not $match.Success) { throw 'Could not find the JSON.parse table in getGraphemeBreakRawData.' }

$values = @($match.Groups[1].Value -split ',' | ForEach-Object { $_.Trim() } | Where-Object { $_ -ne '' })
if ($values.Count % 3 -ne 0) { throw "Expected a multiple of 3 values, got $($values.Count)." }

$lines = for ($i = 0; $i -lt $values.Count; $i += 24) {
    '        ' + (($values[$i..([Math]::Min($i + 23, $values.Count - 1))]) -join ', ')
}

$output = @(
    '// <auto-generated> by eng/Generate-GraphemeBreakData.ps1 from microsoft/vscode src/vs/base/common/strings.ts',
    "// (getGraphemeBreakRawData), commit $commit. Do not edit.",
    '// Copyright (c) Microsoft Corporation. MIT License.',
    '',
    'namespace LoomEditor.Core.Text;',
    '',
    'internal static class GraphemeBreakData',
    '{',
    '    public static ReadOnlySpan<int> Raw =>',
    '    [',
    ($lines -join ",`n"),
    '    ];',
    '}',
    ''
) -join "`n"

$target = Join-Path $PSScriptRoot '../src/LoomEditor.Core/Text/GraphemeBreakData.cs'
[System.IO.File]::WriteAllText($target, $output, [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $($values.Count) values to $target"
