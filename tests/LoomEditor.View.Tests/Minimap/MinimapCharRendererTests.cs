    private static readonly Rgba8 Black = new(0, 0, 0, 255);
    private static readonly Rgba8 White = new(255, 255, 255, 255);

    private static byte[] GetSampleData()
    {
        const int CharCode = 'd';
        var result = new byte[MinimapCharSheet.SampledCharHeight * MinimapCharSheet.SampledCharWidth
            * MinimapCharSheet.RgbaChannelsCnt * MinimapCharSheet.CharCount];

        var rowWidth = MinimapCharSheet.SampledCharWidth * MinimapCharSheet.RgbaChannelsCnt * MinimapCharSheet.CharCount;
        var chIndex = CharCode - MinimapCharSheet.StartChCode;

        var globalOutputOffset = chIndex * MinimapCharSheet.SampledCharWidth * MinimapCharSheet.RgbaChannelsCnt;
        var inputOffset = 0;
        for (var i = 0; i < MinimapCharSheet.SampledCharHeight; i++)
        {
            var outputOffset = globalOutputOffset;
            for (var j = 0; j < MinimapCharSheet.SampledCharWidth; j++)
            {
                for (var channel = 0; channel < MinimapCharSheet.RgbaChannelsCnt; channel++)
                {
                    result[outputOffset] = SampleD[inputOffset];
                    inputOffset++;
                    outputOffset++;
                }
            }

            globalOutputOffset += rowWidth;
        }

        return result;
    }

    private static MinimapImageData BlackImage(int width, int height)
    {
        var imageData = new MinimapImageData(width, height);
        for (var i = 0; i < imageData.Data.Length / 4; i++)
        {
            imageData.Data[(4 * i) + 3] = 255;
        }

        return imageData;
    }

    // Monaco: 'letter d @ 2x'
    [Fact]
    public void LetterD_At2x_RendersMonacoPixels()
    {
        var renderer = MinimapCharRendererFactory.CreateFromSampleData(GetSampleData(), 2);
        var imageData = BlackImage(MinimapCharSheet.BaseCharWidth * 2, MinimapCharSheet.BaseCharHeight * 2);

        renderer.RenderChar(imageData, 0, 0, 'd', White, 255, Black, 255, 2, false, false);

        Assert.Equal(
            new byte[]
            {
                0x2D, 0x2D, 0x2D, 0xFF, 0xAC, 0xAC, 0xAC, 0xFF,
                0xC6, 0xC6, 0xC6, 0xFF, 0xC8, 0xC8, 0xC8, 0xFF,
                0xC0, 0xC0, 0xC0, 0xFF, 0xCB, 0xCB, 0xCB, 0xFF,
                0x00, 0x00, 0x00, 0xFF, 0x00, 0x00, 0x00, 0xFF,
            },
            imageData.Data);
    }

    // Monaco: 'letter d @ 1x'
    [Fact]
    public void LetterD_At1x_RendersMonacoPixels()
    {
        var renderer = MinimapCharRendererFactory.CreateFromSampleData(GetSampleData(), 1);
        var imageData = BlackImage(MinimapCharSheet.BaseCharWidth, MinimapCharSheet.BaseCharHeight);

        renderer.RenderChar(imageData, 0, 0, 'd', White, 255, Black, 255, 1, false, false);

        Assert.Equal(
            new byte[]
            {
                0xCB, 0xCB, 0xCB, 0xFF,
                0x81, 0x81, 0x81, 0xFF,
            },
            imageData.Data);
    }

    [Theory]
    [InlineData(1)]
    [InlineData(2)]
    public void PreBaked_Scale1And2_HaveTheExpectedLength(int scale)
    {
        var data = MinimapPreBaked.Get(scale)!;

        Assert.Equal(
            MinimapCharSheet.CharCount * MinimapCharSheet.BaseCharWidth * scale * MinimapCharSheet.BaseCharHeight * scale,
            data.Length);
    }

    [Fact]
    public void GetCharIndex_OutOfRange_SmallScaleWrapsLargeScaleUsesUnknown()
    {
        Assert.Equal(MinimapCharSheet.CharCount - 1, MinimapCharSheet.GetCharIndex(MinimapCharSheet.UnknownCode, 3));
        Assert.Equal(
            (MinimapCharSheet.UnknownCode - MinimapCharSheet.StartChCode) % MinimapCharSheet.CharCount,
            MinimapCharSheet.GetCharIndex(MinimapCharSheet.UnknownCode, 2));
        Assert.Equal(MinimapCharSheet.CharCount - 1, MinimapCharSheet.GetCharIndex(0, 3));
        Assert.Equal('a' - MinimapCharSheet.StartChCode, MinimapCharSheet.GetCharIndex('a', 3));
    }

    [Fact]
    public void ClampToByte_RoundsHalfToEvenAndClamps()
    {
        Assert.Equal(0, MinimapCharSheet.ClampToByte(0.5));
        Assert.Equal(2, MinimapCharSheet.ClampToByte(1.5));
        Assert.Equal(255, MinimapCharSheet.ClampToByte(300));
        Assert.Equal(0, MinimapCharSheet.ClampToByte(-3));
    }

    [Fact]
    public void BlockRenderChar_FillsTheCell()
    {
        var renderer = MinimapCharRendererFactory.CreateFromSampleData(GetSampleData(), 2);
        var imageData = BlackImage(2, 4);

        renderer.BlockRenderChar(imageData, 0, 0, White, 255, Black, 255, false);

        // 0.5 * 255 = 127.5 -> rounds half to even -> 128.
        for (var i = 0; i < 8; i++)
        {
            Assert.Equal(new byte[] { 128, 128, 128, 255 }, imageData.Data[(4 * i)..((4 * i) + 4)]);
        }
    }
