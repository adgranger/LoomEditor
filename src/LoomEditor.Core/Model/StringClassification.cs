using System.Text.RegularExpressions;

namespace LoomEditor.Core.Model;

/// <summary>Cheap classification of strings: right-to-left text, basic ASCII, unusual line terminators, BOM.</summary>
/// <remarks>
/// <para>Monaco: <c>containsRTL</c>, <c>isBasicASCII</c>, <c>containsUnusualLineTerminators</c>, <c>UTF8_BOM_CHARACTER</c>, <c>startsWithUTF8BOM</c>, <c>firstNonWhitespaceIndex</c>, <c>lastNonWhitespaceIndex</c>.</para>
/// <para>Threading: pure static methods; thread-safe.</para>
/// </remarks>
internal static partial class StringClassification
{
    /// <summary>The UTF-8 byte order mark as a character (Monaco: <c>UTF8_BOM_CHARACTER</c>).</summary>
    public const char Utf8Bom = (char)0xFEFF;

    private const char LineSeparator = (char)0x2028;
    private const char ParagraphSeparator = (char)0x2029;

    // Generated by Monaco using https://github.com/alexdima/unicode-utils/blob/main/rtl-test.js (copied verbatim).
    [GeneratedRegex(@"(?:[\u05BE\u05C0\u05C3\u05C6\u05D0-\u05F4\u0608\u060B\u060D\u061B-\u064A\u066D-\u066F\u0671-\u06D5\u06E5\u06E6\u06EE\u06EF\u06FA-\u0710\u0712-\u072F\u074D-\u07A5\u07B1-\u07EA\u07F4\u07F5\u07FA\u07FE-\u0815\u081A\u0824\u0828\u0830-\u0858\u085E-\u088E\u08A0-\u08C9\u200F\uFB1D\uFB1F-\uFB28\uFB2A-\uFD3D\uFD50-\uFDC7\uFDF0-\uFDFC\uFE70-\uFEFC]|\uD802[\uDC00-\uDD1B\uDD20-\uDE00\uDE10-\uDE35\uDE40-\uDEE4\uDEEB-\uDF35\uDF40-\uDFFF]|\uD803[\uDC00-\uDD23\uDE80-\uDEA9\uDEAD-\uDF45\uDF51-\uDF81\uDF86-\uDFF6]|\uD83A[\uDC00-\uDCCF\uDD00-\uDD43\uDD4B-\uDFFF]|\uD83B[\uDC00-\uDEBB])")]
    private static partial Regex RtlRegex();

    /// <summary>True when <paramref name="text"/> contains any character classified as "R" or "AL" (Monaco: <c>containsRTL</c>).</summary>
    public static bool ContainsRtl(string text)
    {
        ArgumentNullException.ThrowIfNull(text);
        return RtlRegex().IsMatch(text);
    }

    /// <summary>True when <paramref name="text"/> has only tab, <c>\n</c>, <c>\r</c> and characters 32..126 (Monaco: <c>isBasicASCII</c>).</summary>
    public static bool IsBasicAscii(string text)
    {
        ArgumentNullException.ThrowIfNull(text);
        foreach (char c in text)
        {
            if (c is not ('\t' or '\n' or '\r') && (c < 0x20 || c > 0x7E))
            {
                return false;
            }
        }

        return true;
    }

    /// <summary>True when <paramref name="text"/> contains U+2028 or U+2029 (Monaco: <c>containsUnusualLineTerminators</c>).</summary>
    public static bool ContainsUnusualLineTerminators(string text)
    {
        ArgumentNullException.ThrowIfNull(text);
        return text.AsSpan().ContainsAny(LineSeparator, ParagraphSeparator);
    }

    /// <summary>True when the first character of <paramref name="text"/> is the UTF-8 BOM (Monaco: <c>startsWithUTF8BOM</c>).</summary>
    public static bool StartsWithUtf8Bom(string text)
    {
        ArgumentNullException.ThrowIfNull(text);
        return text.Length > 0 && text[0] == Utf8Bom;
    }

    /// <summary>The index of the first character that is not a space or tab, or -1 (Monaco: <c>firstNonWhitespaceIndex</c>).</summary>
    public static int FirstNonWhitespaceIndex(string text)
    {
        ArgumentNullException.ThrowIfNull(text);
        for (int i = 0; i < text.Length; i++)
        {
            if (text[i] is not (' ' or '\t'))
            {
                return i;
            }
        }

        return -1;
    }

    /// <summary>The index of the last character that is not a space or tab, or -1 (Monaco: <c>lastNonWhitespaceIndex</c>).</summary>
    public static int LastNonWhitespaceIndex(string text)
    {
        ArgumentNullException.ThrowIfNull(text);
        for (int i = text.Length - 1; i >= 0; i--)
        {
            if (text[i] is not (' ' or '\t'))
            {
                return i;
            }
        }

        return -1;
    }
}
